#!/usr/bin/env python3
"""Regenerates Sources/TasjeelCore/RemotionTemplate.swift from the folders in Templates.

Each template is kept as ordinary files so it can be edited, type-checked and
run with Remotion. The app has no resource bundle, so this script copies the
files into a Swift source file as string literals. Run it after changing
anything under Templates; a test fails if the two drift apart.
"""
import os

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
target = os.path.join(root, "Sources", "TasjeelCore", "RemotionTemplate.swift")

# Folder under Templates/ and the Swift name its files are stored under.
templates = [
    ("remotion", "files", "The project a recording is exported into."),
    ("studio", "studioFiles", "The project a storyboard is built into."),
]


def read(folder):
    source = os.path.join(root, "Templates", folder)
    entries = []
    for directory, _, names in os.walk(source):
        for name in names:
            if name == ".DS_Store":
                continue
            path = os.path.join(directory, name)
            with open(path, encoding="utf-8") as handle:
                entries.append((os.path.relpath(path, source), handle.read()))
    return sorted(entries)


out = [
    "// Generated by scripts/embed-remotion-template.py from the folders in Templates.",
    "// Do not edit by hand: change the template files and run the script.",
    "",
    "enum RemotionTemplate {",
    "    /// Path inside the project and the file's text. `__NAME__` and",
    "    /// `__TITLE__` are filled in when a project is written.",
    "    typealias File = (path: String, text: String)",
]
total = 0
for folder, name, comment in templates:
    entries = read(folder)
    total += len(entries)
    out += ["", f"    /// {comment} From Templates/{folder}.", f"    static let {name}: [File] = ["]
    for relative, text in entries:
        assert '"""#' not in text and "\\#(" not in text, relative
        out.append(f'        ("{relative}", #"""')
        out.extend(text.split("\n")[:-1] if text.endswith("\n") else text.split("\n"))
        # The closing quotes sit at column 0 so that no indentation is stripped.
        out.append('"""# + "\\n"),' if text.endswith("\n") else '"""#),')
    out.append("    ]")
out += ["}", ""]

with open(target, "w", encoding="utf-8") as handle:
    handle.write("\n".join(out))
print(f"wrote {total} files into {os.path.relpath(target, root)}")
